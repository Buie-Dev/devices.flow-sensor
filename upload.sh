#!/bin/bash

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PORT="/dev/cu.SLAB_USBtoUART"

echo "=== ESP32 Flow Sensor Upload ==="
echo ""

# ─── Check port exists ────────────────────────────────────────
if [ ! -e "$PORT" ]; then
  echo "ERROR: Port $PORT not found."
  echo ""
  echo "  - Try a different USB cable (many are charge-only)"
  echo "  - Install the CP210x driver from Silicon Labs"
  echo "  - Hold BOOT, tap EN, release BOOT on the ESP32"
  exit 1
fi

echo "Port: $PORT"
echo ""

# ─── Load .env ────────────────────────────────────────────────
ENV_FILE="$SCRIPT_DIR/.env"
if [ ! -f "$ENV_FILE" ]; then
  echo "ERROR: .env file not found at $ENV_FILE"
  echo "  Copy .env.example to .env and fill in your values."
  exit 1
fi
export $(grep -v '^#' "$ENV_FILE" | grep -v '^$' | xargs)

# ─── Generate config.py from .env ─────────────────────────────
cat > "$SCRIPT_DIR/config.py" <<EOF
# Auto-generated by upload.sh from .env — do not edit directly.

WIFI_SSID = "$WIFI_SSID"
WIFI_PASSWORD = "$WIFI_PASSWORD"

MQTT_BROKER = "$MQTT_BROKER"
MQTT_PORT = $MQTT_PORT
MQTT_USER = "$MQTT_USER"
MQTT_PASSWORD = "$MQTT_PASSWORD"

SENSOR_NAME = "$SENSOR_NAME"
EOF

# ─── Upload files ─────────────────────────────────────────────
echo "Uploading config.py..."
mpremote connect "$PORT" cp "$SCRIPT_DIR/config.py" :config.py
if [ $? -ne 0 ]; then
  echo "ERROR: Failed to upload config.py"
  exit 1
fi

echo "Uploading index.py as main.py..."
mpremote connect "$PORT" cp "$SCRIPT_DIR/index.py" :main.py
if [ $? -ne 0 ]; then
  echo "ERROR: Failed to upload index.py"
  exit 1
fi

# ─── Verify ───────────────────────────────────────────────────
echo ""
echo "Verifying files on device:"
mpremote connect "$PORT" ls

echo ""
echo "Rebooting device..."
mpremote connect "$PORT" reset

echo ""
echo "=== Upload complete ==="
echo "Run this to watch boot output (Ctrl+] to exit):"
echo "  mpremote connect $PORT repl"
